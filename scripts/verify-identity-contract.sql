-- Independent expected physical contract from Issues #26 and #28 (IAM-OPEN-07).
-- Verification reference only. Never generated from a tested target or applied as a migration.
CREATE TABLE identity.roles (
    id uuid NOT NULL CONSTRAINT pk_roles PRIMARY KEY,
    name varchar(256) NOT NULL,
    normalized_name varchar(256) NOT NULL,
    concurrency_stamp text NOT NULL,
    CONSTRAINT ck_roles_uuid_v4 CHECK (get_byte(uuid_send(id), 6) >> 4 = 4 AND get_byte(uuid_send(id), 8) >> 6 = 2),
    CONSTRAINT ck_roles_normalized_name CHECK (length(btrim(normalized_name)) > 0)
);
CREATE TABLE identity.users (
    id uuid NOT NULL CONSTRAINT pk_users PRIMARY KEY,
    user_name varchar(256) NOT NULL,
    normalized_user_name varchar(256) NOT NULL,
    email varchar(256) NOT NULL,
    normalized_email varchar(256) NOT NULL,
    email_confirmed boolean NOT NULL,
    password_hash text NULL,
    security_stamp text NOT NULL,
    concurrency_stamp text NOT NULL,
    phone_number text NULL,
    phone_number_confirmed boolean NOT NULL,
    two_factor_enabled boolean NOT NULL,
    lockout_end timestamptz NULL,
    lockout_enabled boolean NOT NULL,
    access_failed_count integer NOT NULL,
    CONSTRAINT ck_users_uuid_v4 CHECK (get_byte(uuid_send(id), 6) >> 4 = 4 AND get_byte(uuid_send(id), 8) >> 6 = 2),
    CONSTRAINT ck_users_access_failed_count CHECK (access_failed_count >= 0),
    CONSTRAINT ck_users_normalized_user_name CHECK (length(btrim(normalized_user_name)) > 0),
    CONSTRAINT ck_users_normalized_email CHECK (length(btrim(normalized_email)) > 0)
);
CREATE TABLE identity.role_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_role_claims PRIMARY KEY,
    role_id uuid NOT NULL,
    claim_type text NULL,
    claim_value text NULL,
    CONSTRAINT fk_role_claims_roles FOREIGN KEY (role_id) REFERENCES identity.roles(id) ON DELETE CASCADE
);
CREATE TABLE identity.user_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_user_claims PRIMARY KEY,
    user_id uuid NOT NULL,
    claim_type text NULL,
    claim_value text NULL,
    CONSTRAINT fk_user_claims_users FOREIGN KEY (user_id) REFERENCES identity.users(id) ON DELETE CASCADE
);
CREATE TABLE identity.user_logins (
    login_provider varchar(128) NOT NULL,
    provider_key varchar(128) NOT NULL,
    provider_display_name text NULL,
    user_id uuid NOT NULL,
    CONSTRAINT pk_user_logins PRIMARY KEY (login_provider, provider_key),
    CONSTRAINT fk_user_logins_users FOREIGN KEY (user_id) REFERENCES identity.users(id) ON DELETE CASCADE
);
CREATE TABLE identity.user_roles (
    user_id uuid NOT NULL,
    role_id uuid NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_users FOREIGN KEY (user_id) REFERENCES identity.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_roles FOREIGN KEY (role_id) REFERENCES identity.roles(id) ON DELETE CASCADE
);
CREATE TABLE identity.user_tokens (
    user_id uuid NOT NULL,
    login_provider varchar(128) NOT NULL,
    name varchar(128) NOT NULL,
    value text NULL,
    CONSTRAINT pk_user_tokens PRIMARY KEY (user_id, login_provider, name),
    CONSTRAINT fk_user_tokens_users FOREIGN KEY (user_id) REFERENCES identity.users(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX ux_users_normalized_user_name ON identity.users(normalized_user_name);
CREATE UNIQUE INDEX ux_users_normalized_email ON identity.users(normalized_email);
CREATE UNIQUE INDEX ux_roles_normalized_name ON identity.roles(normalized_name);
CREATE INDEX ix_user_roles_role_id ON identity.user_roles(role_id);
CREATE INDEX ix_user_claims_user_id ON identity.user_claims(user_id);
CREATE INDEX ix_role_claims_role_id ON identity.role_claims(role_id);
CREATE INDEX ix_user_logins_user_id ON identity.user_logins(user_id);
